using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;

namespace VitaSharp.Core.Generators;

/// <summary>
/// Emits the NID database (<c>VitaSharp.Core.Hle.NidDatabase</c>) from <c>Hle/Data/nids.txt</c> (an AdditionalFiles
/// item, one "0xNID module library name" per line): the entries in the file's order as constant spans (the NIDs, the
/// start of each name in one text constant, the module and library of each as an index into a small string table) and
/// two index spans, by NID and by name (ordinal), for binary searches. The table is data of the assembly: nothing is
/// read, split or allocated when the emulator starts (the parse of the embedded text took ~45 ms and 10 MB at every
/// start).
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class NidTableGenerator : IIncrementalGenerator
{
    private const string FileName = "nids.txt";

    private static readonly DiagnosticDescriptor s_badLine = new(
        "VSNID001", "Malformed NID line", "nids.txt line {0}: '{1}' is not '0xNID module library name'", "VitaSharp.Nids", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<AdditionalText> files = context.AdditionalTextsProvider
            .Where(static file => string.Equals(Path.GetFileName(file.Path), FileName, StringComparison.OrdinalIgnoreCase));
        context.RegisterSourceOutput(files, static (spc, file) => Emit(spc, file));
    }

    private sealed class Entry
    {
        public uint Nid;
        public string Module = "";
        public string Library = "";
        public string Name = "";
    }

    private static void Emit(SourceProductionContext spc, AdditionalText file)
    {
        SourceText? text = file.GetText(spc.CancellationToken);
        if (text == null)
        {
            return;
        }

        List<Entry> entries = [];
        foreach (TextLine line in text.Lines)
        {
            string content = line.ToString().Trim();
            if (content.Length == 0)
            {
                continue;
            }

            string[] parts = content.Split(' ');
            if (parts.Length < 4 || !parts[0].StartsWith("0x", StringComparison.Ordinal)
                || !uint.TryParse(parts[0].Substring(2), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out uint nid))
            {
                spc.ReportDiagnostic(Diagnostic.Create(s_badLine, Location.None, line.LineNumber + 1, content));
                continue;
            }

            entries.Add(new Entry { Nid = nid, Module = parts[1], Library = parts[2], Name = parts[3] });
        }

        List<string> strings = [];
        Dictionary<string, int> stringIndex = new(StringComparer.Ordinal);
        int IndexOf(string value)
        {
            if (!stringIndex.TryGetValue(value, out int index))
            {
                index = strings.Count;
                strings.Add(value);
                stringIndex[value] = index;
            }

            return index;
        }

        StringBuilder names = new();
        int[] nameStart = new int[entries.Count + 1];
        int[] module = new int[entries.Count];
        int[] library = new int[entries.Count];
        for (int i = 0; i < entries.Count; i++)
        {
            nameStart[i] = names.Length;
            names.Append(entries[i].Name);
            module[i] = IndexOf(entries[i].Module);
            library[i] = IndexOf(entries[i].Library);
        }

        nameStart[entries.Count] = names.Length;
        int[] byNid = Enumerable.Range(0, entries.Count).OrderBy(i => entries[i].Nid).ThenBy(i => i).ToArray();
        int[] byName = Enumerable.Range(0, entries.Count).OrderBy(i => entries[i].Name, StringComparer.Ordinal).ThenBy(i => i).ToArray();
        int unique = entries.Select(entry => entry.Nid).Distinct().Count();

        StringBuilder sb = new();
        sb.AppendLine("// <auto-generated/> by VitaSharp.Core.Generators.NidTableGenerator from nids.txt");
        sb.AppendLine("namespace VitaSharp.Core.Hle;");
        sb.AppendLine();
        sb.AppendLine("public static partial class NidDatabase");
        sb.AppendLine("{");
        sb.AppendLine($"    private const int EntryCount = {entries.Count};");
        sb.AppendLine($"    private const int UniqueCount = {unique};");
        sb.Append("    private const string NameText = \"").Append(names).AppendLine("\";");
        AppendSpan(sb, "uint", "EntryNid", entries.Select(entry => "0x" + entry.Nid.ToString("X8", CultureInfo.InvariantCulture)));
        AppendSpan(sb, "int", "EntryNameStart", nameStart.Select(value => value.ToString(CultureInfo.InvariantCulture)));
        AppendSpan(sb, "ushort", "EntryModule", module.Select(value => value.ToString(CultureInfo.InvariantCulture)));
        AppendSpan(sb, "ushort", "EntryLibrary", library.Select(value => value.ToString(CultureInfo.InvariantCulture)));
        AppendSpan(sb, "ushort", "ByNid", byNid.Select(value => value.ToString(CultureInfo.InvariantCulture)));
        AppendSpan(sb, "ushort", "ByName", byName.Select(value => value.ToString(CultureInfo.InvariantCulture)));
        sb.AppendLine("    private static string StringAt(int index) => index switch");
        sb.AppendLine("    {");
        for (int i = 0; i < strings.Count; i++)
        {
            sb.Append("        ").Append(i.ToString(CultureInfo.InvariantCulture)).Append(" => \"").Append(strings[i]).AppendLine("\",");
        }

        sb.AppendLine("        _ => \"\",");
        sb.AppendLine("    };");
        sb.AppendLine("}");
        spc.AddSource("NidDatabase.Table.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void AppendSpan(StringBuilder sb, string type, string name, IEnumerable<string> values)
    {
        sb.Append("    private static global::System.ReadOnlySpan<").Append(type).Append("> ").Append(name).Append(" => [");
        int column = 0;
        foreach (string value in values)
        {
            if (column++ % 16 == 0)
            {
                sb.AppendLine();
                sb.Append("        ");
            }

            sb.Append(value).Append(", ");
        }

        sb.AppendLine();
        sb.AppendLine("    ];");
    }
}
