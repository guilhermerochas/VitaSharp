using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace VitaSharp.Core.Generators;

/// <summary>
/// Emits <c>HleBindings.GeneratedModules()</c>: one entry per concrete <c>HleModule</c> subclass (with a factory) and,
/// for each of its instance methods marked <c>[Hle]</c>, a binding with the attribute data and an invoker factory.
/// The invoker reads the arguments exactly like the former System.Linq.Expressions binder (AAPCS-VFP as used by the
/// Vita: 32-bit integers, pointers, strings and bools in r0-r3 then the stack, 64-bit integers and doubles in an even
/// register pair or 8-byte aligned stack slot, floats in s0-s15, <c>VarArgs</c> starting at the next core register,
/// <c>HleContext</c> passed through) and converts the return value to the matching <c>HleContext.Return</c> overload.
/// Private methods are called through <c>[UnsafeAccessor]</c>, so modules need no changes. Each binding also carries
/// a layout string (see <see cref="Layout"/>) that tests compare against a reflection-based reference binder.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class HleBinderGenerator : IIncrementalGenerator
{
    const string HleModuleName = "VitaSharp.Core.Hle.HleModule";
    const string HleAttributeName = "VitaSharp.Core.Hle.HleAttribute";
    const string HleContextName = "VitaSharp.Core.Hle.HleContext";
    const string VarArgsName = "VitaSharp.Core.Hle.VarArgs";
    const string PtrName = "VitaSharp.Core.Memory.Ptr<T>";

    static readonly DiagnosticDescriptor Unsupported = new(
        "VSHLE001", "Unsupported HLE signature", "HLE method {0}: {1}", "VitaSharp.Hle", DiagnosticSeverity.Error, true);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var modules = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
                static (ctx, ct) => ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct) as INamedTypeSymbol)
            .Where(static t => t is not null)
            .Collect();
        context.RegisterSourceOutput(modules.Combine(context.CompilationProvider), static (spc, pair) => Emit(spc, pair.Left!, pair.Right));
    }

    static bool DerivesFrom(INamedTypeSymbol t, INamedTypeSymbol baseType)
    {
        for (var b = t.BaseType; b != null; b = b.BaseType)
            if (SymbolEqualityComparer.Default.Equals(b, baseType)) return true;
        return false;
    }

    static void Emit(SourceProductionContext spc, ImmutableArray<INamedTypeSymbol?> candidates, Compilation compilation)
    {
        var moduleBase = compilation.GetTypeByMetadataName(HleModuleName);
        var hleAttr = compilation.GetTypeByMetadataName(HleAttributeName);
        if (moduleBase == null || hleAttr == null) return; // not the core assembly
        var types = candidates.Where(t => t != null).Select(t => t!).Where(t => !t.IsAbstract && t.TypeKind == TypeKind.Class && DerivesFrom(t, moduleBase))
            .Distinct<INamedTypeSymbol>(SymbolEqualityComparer.Default)
            .OrderBy(t => t!.ToDisplayString(), System.StringComparer.Ordinal) // stable output; registration order is decided at run time
            .ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> by VitaSharp.Core.Generators.HleBinderGenerator");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("#pragma warning disable CS0618 // [Obsolete] HLE methods are still bound");
        // the core implements HleBindings.GeneratedModules(); any other assembly using the generator (the tests' probe
        // modules) gets its own internal table
        bool core = compilation.AssemblyName == "VitaSharp.Core";
        if (core)
        {
            sb.AppendLine("namespace VitaSharp.Core.Hle;");
            sb.AppendLine();
            sb.AppendLine("public static partial class HleBindings");
            sb.AppendLine("{");
            sb.AppendLine("    private static partial global::VitaSharp.Core.Hle.HleModuleEntry[] GeneratedModules() => new global::VitaSharp.Core.Hle.HleModuleEntry[]");
        }
        else
        {
            sb.AppendLine("namespace VitaSharp.Generated;");
            sb.AppendLine();
            sb.AppendLine("internal static class HleLocalBindings");
            sb.AppendLine("{");
            sb.AppendLine("    public static global::VitaSharp.Core.Hle.HleModuleEntry[] Modules() => new global::VitaSharp.Core.Hle.HleModuleEntry[]");
        }
        sb.AppendLine("    {");
        for (int i = 0; i < types.Count; i++)
        {
            var t = types[i]!;
            sb.AppendLine($"        new(typeof({Fq(t)}), static () => new {Fq(t)}(), M{i}),");
        }
        sb.AppendLine("    };");

        var accessors = new StringBuilder();
        int accessorId = 0;
        for (int i = 0; i < types.Count; i++)
        {
            var t = types[i]!;
            sb.AppendLine();
            sb.AppendLine($"    // {t.ToDisplayString()}");
            sb.AppendLine($"    static global::VitaSharp.Core.Hle.HleBinding[] M{i}() => new global::VitaSharp.Core.Hle.HleBinding[]");
            sb.AppendLine("    {");
            // GetMembers keeps declaration order (partial parts in syntax tree order), like reflection's metadata order
            foreach (var m in t.GetMembers().OfType<IMethodSymbol>())
            {
                if (m.IsStatic || m.MethodKind != MethodKind.Ordinary) continue;
                var attrs = m.GetAttributes().Where(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, hleAttr)).ToList();
                if (attrs.Count == 0) continue;
                if (!TryBuild(m, compilation, out var layout, out var call, out string? error))
                {
                    spc.ReportDiagnostic(Diagnostic.Create(Unsupported, m.Locations.FirstOrDefault(), $"{t.Name}.{m.Name}", error));
                    continue;
                }
                string target;
                if (IsAccessible(m)) target = $"self.{m.Name}";
                else
                {
                    target = $"A{accessorId}";
                    accessors.AppendLine($"    [global::System.Runtime.CompilerServices.UnsafeAccessor(global::System.Runtime.CompilerServices.UnsafeAccessorKind.Method, Name = \"{m.Name}\")]");
                    accessors.Append($"    static extern {(m.ReturnsVoid ? "void" : Fq(m.ReturnType))} A{accessorId}({Fq(t)} self");
                    foreach (var p in m.Parameters) accessors.Append($", {Fq(p.Type)} {Escape(p.Name)}");
                    accessors.AppendLine(");");
                    accessorId++;
                }
                foreach (var a in attrs)
                {
                    string? name = a.ConstructorArguments.Length > 0 ? a.ConstructorArguments[0].Value as string : null;
                    uint nid = 0;
                    string? library = null;
                    foreach (var na in a.NamedArguments)
                    {
                        if (na.Key == "Nid" && na.Value.Value is uint n) nid = n;
                        else if (na.Key == "Library") library = na.Value.Value as string;
                    }
                    string invocation = target.StartsWith("self.") ? $"{target}({call.Args})" : $"{target}(self{(call.Args.Length > 0 ? ", " + call.Args : "")})";
                    sb.AppendLine($"        new(\"{m.Name}\", {Str(name)}, 0x{nid:X8}u, {Str(library)}, {Str(layout)},");
                    sb.AppendLine($"            static m => {{ var self = ({Fq(t)})m; return ctx => {{ unchecked {{ {call.Wrap(invocation)}; }} }}; }}),");
                }
            }
            sb.AppendLine("    };");
        }
        if (accessors.Length > 0)
        {
            sb.AppendLine();
            sb.Append(accessors);
        }
        sb.AppendLine("}");
        spc.AddSource("HleBindings.g.cs", sb.ToString());
    }

    sealed class Call
    {
        public string Args = "";
        public string Return = ""; // "" = void, else normalized type keyword
        public string ReturnConv = "";
        public string Wrap(string invocation) => Return.Length == 0 ? invocation : $"ctx.Return({string.Format(ReturnConv, invocation)})";
    }

    /// <summary>
    /// Argument layout description shared with the reflection reference binder in the tests: one token per parameter
    /// ("ctx", "va@N" = VarArgs from core slot N, "sN" = float register, "rN" / "rNrM" = core register(s),
    /// "spO" / "spO+8" = stack word(s) at byte offset O), each followed by "=" and the conversion, then "->" and the
    /// return conversion.
    /// </summary>
    static bool TryBuild(IMethodSymbol m, Compilation c, out string layout, out Call call, out string? error)
    {
        call = new Call();
        error = null;
        var sbLayout = new StringBuilder();
        var args = new List<string>();
        int gpr = 0, stack = 0, fpr = 0;
        const string Ctx = "global::VitaSharp.Core.Hle.HleContext";
        foreach (var p in m.Parameters)
        {
            if (p.RefKind != RefKind.None) { layout = ""; error = $"parameter {p.Name} is passed by reference"; return false; }
            var t = p.Type;
            string token, raw, rawType;
            if (sbLayout.Length > 0) sbLayout.Append(',');
            if (t.ToDisplayString() == HleContextName) { args.Add("ctx"); sbLayout.Append("ctx"); continue; }
            if (t.ToDisplayString() == VarArgsName) { args.Add($"new global::VitaSharp.Core.Hle.VarArgs(ctx, {gpr})"); sbLayout.Append($"va@{gpr}"); continue; }
            if (t.SpecialType == SpecialType.System_Single) { args.Add($"{Ctx}.ArgF32(ctx, {fpr})"); sbLayout.Append($"s{fpr}=float"); fpr++; continue; }
            bool wide = t.SpecialType is SpecialType.System_Int64 or SpecialType.System_UInt64 or SpecialType.System_Double;
            if (wide)
            {
                if ((gpr & 1) != 0) gpr++;
                if (gpr + 2 <= 4) { raw = $"{Ctx}.ArgU64(ctx, {gpr})"; token = $"r{gpr}r{gpr + 1}"; gpr += 2; }
                else { gpr = 4; stack = (stack + 7) & ~7; raw = $"{Ctx}.ArgU64Stack(ctx, {stack})"; token = $"sp{stack}+8"; stack += 8; }
                rawType = "ulong";
            }
            else
            {
                if (gpr < 4) { raw = $"{Ctx}.ArgU32(ctx, {gpr})"; token = $"r{gpr}"; gpr++; }
                else { raw = $"{Ctx}.ArgStack(ctx, {stack})"; token = $"sp{stack}"; stack += 4; }
                rawType = "uint";
            }
            if (!TryConvert(raw, rawType, t, out string expr, out string conv)) { layout = ""; error = $"parameter type {t.ToDisplayString()} is not supported"; return false; }
            if (!IsAccessible(t)) { layout = ""; error = $"parameter type {t.ToDisplayString()} is not accessible from generated code: make it internal"; return false; }
            args.Add(expr);
            sbLayout.Append(token).Append('=').Append(conv);
        }
        call.Args = string.Join(", ", args);
        sbLayout.Append("->");
        if (m.ReturnsVoid) sbLayout.Append("void");
        else
        {
            var rt = m.ReturnType;
            if (!IsAccessible(rt)) { layout = ""; error = $"return type {rt.ToDisplayString()} is not accessible from generated code"; return false; }
            string norm = NormalizeReturn(rt);
            call.Return = norm;
            if (Name(rt) == norm) { call.ReturnConv = "{0}"; sbLayout.Append(norm); }
            else if (IsPtr(rt)) { call.ReturnConv = "{0}.Address"; sbLayout.Append($"{norm}<-ptr"); }
            else if (rt.SpecialType is SpecialType.System_String || rt.IsReferenceType || (rt.TypeKind == TypeKind.Struct && rt.SpecialType == SpecialType.None && rt.TypeKind != TypeKind.Enum))
            { layout = ""; error = $"return type {rt.ToDisplayString()} is not supported"; return false; }
            else { call.ReturnConv = $"({norm})({{0}})"; sbLayout.Append($"{norm}<-{Name(rt)}"); }
        }
        layout = sbLayout.ToString();
        return true;
    }

    static bool IsPtr(ITypeSymbol t) => t is INamedTypeSymbol { IsGenericType: true } n && n.ConstructedFrom.ToDisplayString() == PtrName;

    static bool TryConvert(string raw, string rawType, ITypeSymbol t, out string expr, out string conv)
    {
        string name = Name(t);
        conv = name;
        if (name == rawType) { expr = raw; return true; }
        if (t.SpecialType == SpecialType.System_String) { expr = $"global::VitaSharp.Core.Hle.HleContext.ArgString({raw})"; return true; }
        if (t.SpecialType == SpecialType.System_Boolean) { expr = $"({raw} != 0u)"; return true; }
        if (IsPtr(t)) { expr = $"new {Fq(t)}({raw})"; return true; }
        if (t.SpecialType == SpecialType.System_Double) { expr = $"global::System.BitConverter.UInt64BitsToDouble({raw})"; return true; }
        if (t.TypeKind == TypeKind.Enum && t is INamedTypeSymbol { EnumUnderlyingType: { } u })
        {
            expr = $"({Fq(t)})({Fq(u)})({raw})";
            return true;
        }
        if (t.SpecialType is SpecialType.System_Int32 or SpecialType.System_UInt32 or SpecialType.System_Int64 or SpecialType.System_UInt64
            or SpecialType.System_Int16 or SpecialType.System_UInt16 or SpecialType.System_Byte or SpecialType.System_SByte or SpecialType.System_Char)
        {
            expr = $"({Fq(t)})({raw})";
            return true;
        }
        expr = "";
        return false;
    }

    /// <summary>Same rules as the old binder: the HleContext.Return overload a return type maps to.</summary>
    static string NormalizeReturn(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Int32: return "int";
            case SpecialType.System_UInt32: return "uint";
            case SpecialType.System_UInt64: return "ulong";
            case SpecialType.System_Int64: return "long";
            case SpecialType.System_Single: return "float";
            case SpecialType.System_Boolean: return "bool";
            case SpecialType.System_Double: return "double";
            case SpecialType.System_Int16: case SpecialType.System_SByte: return "int";
        }
        if (t.TypeKind == TypeKind.Enum && t is INamedTypeSymbol { EnumUnderlyingType: { } u }) return NormalizeReturn(u);
        return "uint"; // ushort, byte, Ptr<T>
    }

    /// <summary>Canonical type name used in layout strings (C# keywords for primitives, dotted full names otherwise).</summary>
    public static string Name(ITypeSymbol t)
    {
        switch (t.SpecialType)
        {
            case SpecialType.System_Int32: return "int";
            case SpecialType.System_UInt32: return "uint";
            case SpecialType.System_Int64: return "long";
            case SpecialType.System_UInt64: return "ulong";
            case SpecialType.System_Int16: return "short";
            case SpecialType.System_UInt16: return "ushort";
            case SpecialType.System_Byte: return "byte";
            case SpecialType.System_SByte: return "sbyte";
            case SpecialType.System_Single: return "float";
            case SpecialType.System_Double: return "double";
            case SpecialType.System_Boolean: return "bool";
            case SpecialType.System_String: return "string";
            case SpecialType.System_Char: return "char";
        }
        if (t is INamedTypeSymbol { IsGenericType: true } g)
            return $"{QualifiedName(g.ConstructedFrom)}<{string.Join(",", g.TypeArguments.Select(Name))}>";
        return QualifiedName(t);
    }

    static string QualifiedName(ITypeSymbol t)
    {
        string n = t.Name;
        for (var c = t.ContainingType; c != null; c = c.ContainingType) n = c.Name + "." + n;
        var ns = t.ContainingNamespace;
        return ns == null || ns.IsGlobalNamespace ? n : ns.ToDisplayString() + "." + n;
    }

    static string Fq(ITypeSymbol t) => t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    static string Str(string? s) => s == null ? "null" : "\"" + s.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    static string Escape(string name) => Microsoft.CodeAnalysis.CSharp.SyntaxFacts.GetKeywordKind(name) != Microsoft.CodeAnalysis.CSharp.SyntaxKind.None ? "@" + name : name;

    /// <summary>Whether generated code elsewhere in the assembly can name the member (internal or wider all the way up).</summary>
    static bool IsAccessible(ISymbol s)
    {
        switch (s)
        {
            case IArrayTypeSymbol a: return IsAccessible(a.ElementType);
            case IPointerTypeSymbol p: return IsAccessible(p.PointedAtType);
            case ITypeParameterSymbol: return false;
        }
        for (var x = s; x != null && x is not INamespaceSymbol; x = x.ContainingSymbol)
        {
            if (x.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal) return false;
            if (x is INamedTypeSymbol { IsGenericType: true } g && g.TypeArguments.Any(a => !IsAccessible(a))) return false;
        }
        return true;
    }
}
