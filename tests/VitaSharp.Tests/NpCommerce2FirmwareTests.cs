/// <summary>
/// Every result parser of np_commerce2.suprx (the SceNpCommerce2 system NIDs, NpCommerce2.Parsers*.cs) against the
/// firmware: each NID runs a set of crafted store replies (every item tag in plain, tag-1 and tag-2 sections, with
/// strings, section counts and nested blocks after the item's fixed part; the same without them; cut one byte short;
/// an index past the end; NULL arguments) and logs its result and the record it filled (addresses as offsets into the
/// reply). With the firmware's np_commerce2.suprx at hand the same scenarios run through the module's exports and the
/// logs must match; without it the HLE logs are checked against the hashes of the firmware's logs
/// (<see cref="NpCommerce2FirmwareGolden"/>, regenerated by the firmware test when they change).
/// </summary>
[Collection("guest")]
public sealed class NpCommerce2FirmwareTests(GuestMemoryFixture fx, ITestOutputHelper output)
{
    [Fact]
    public void Hle_MatchesTheFirmwareLogs()
    {
        using var h = new C2Harness(fx, null);
        var bad = new List<string>();
        int parsed = 0;
        var unparsed = new List<string>();
        foreach (var p in C2Harness.Parsers)
        {
            var log = h.Run(p, lle: false);
            // the reply with everything in it parses: a record, not an error code
            if (log.FirstOrDefault(l => l.StartsWith("full: ", StringComparison.Ordinal) || l.StartsWith("[0] full: ", StringComparison.Ordinal)) is { } full
                && full.Split(": ")[1] is var r && !(r.Length == 8 && r.StartsWith("80", StringComparison.Ordinal)))
            {
                parsed++;
            }
            else
            {
                unparsed.Add($"{p.Method.Name} {log.FirstOrDefault(l => l.Contains("full: "))}");
            }

            string hash = C2Harness.Hash(log);
            if (!NpCommerce2FirmwareGolden.Hashes.TryGetValue(p.Nid, out var want))
            {
                bad.Add($"{p.Nid:X8} {p.Method.Name}: no firmware hash");
            }
            else if (want != hash)
            {
                bad.Add($"{p.Nid:X8} {p.Method.Name}: {hash} (firmware {want})\n  " + string.Join("\n  ", log.Take(40)));
            }
        }
        Assert.True(bad.Count == 0, $"{bad.Count} of {C2Harness.Parsers.Count} parsers differ from the firmware:\n" + string.Join("\n", bad.Take(10)));
        output.WriteLine($"{parsed} of {C2Harness.Parsers.Count} parsers fill their record from the full reply");
        Assert.True(parsed * 10 >= C2Harness.Parsers.Count * 8, $"only {parsed} of {C2Harness.Parsers.Count} parsers parse the full reply:\n" + string.Join("\n", unparsed));
    }

    /// <summary>The 155 SceNpCommerce2 NIDs of NpCommerce2ParserTests less the four helpers that read no reply.</summary>
    [Fact]
    public void EveryParserNidIsCovered() => Assert.Equal(151, C2Harness.Parsers.Count);

    [C2FirmwareFact]
    public void MatchesFirmwareModule()
    {
        using var h = new C2Harness(fx, C2Firmware.ModulePath);
        var bad = new List<string>();
        var golden = new StringBuilder();
        foreach (var p in C2Harness.Parsers)
        {
            var lle = h.Run(p, lle: true);
            var hle = h.Run(p, lle: false);
            golden.AppendLine($"        [0x{p.Nid:X8}] = \"{C2Harness.Hash(lle)}\", // {p.Method.Name}");
            int i = 0;
            while (i < lle.Count && i < hle.Count && lle[i] == hle[i])
            {
                i++;
            }

            if (i < lle.Count || i < hle.Count)
            {
                bad.Add($"{p.Nid:X8} {p.Method.Name}: line {i}\n  fw:  {(i < lle.Count ? lle[i] : "<end>")}\n  hle: {(i < hle.Count ? hle[i] : "<end>")}");
            }
        }
        output.WriteLine(golden.ToString());
        Assert.True(bad.Count == 0, $"{bad.Count} of {C2Harness.Parsers.Count} parsers differ from the firmware:\n" + string.Join("\n", bad.Take(20)));
        // the hashes the HLE test checks without the module must be these firmware logs
        var stale = C2Harness.Parsers.Where(p => NpCommerce2FirmwareGolden.Hashes.GetValueOrDefault(p.Nid) != C2Harness.Hash(h.Run(p, lle: true))).ToList();
        Assert.True(stale.Count == 0, $"{stale.Count} firmware hashes in NpCommerce2FirmwareGolden are out of date; the table:\n" + golden);
    }
}

/// <summary>Runs one np_commerce2 parser NID on the crafted replies, through the HLE or the firmware module.</summary>
sealed class C2Harness : IDisposable
{
    const uint LibNid = 0x40120DC3, InitNid = 0xC73F209A;
    const uint Fill = 0xCDCDCDCD, RecSize = 0x110;
    readonly Emulator _emu;
    readonly string _root;
    readonly NpCommerce2 _hle;
    readonly uint _arena;
    const uint ArenaSize = 0x40_0000;
    uint _bump;
    readonly GuestThread? _thread;
    readonly Queue<(Action<GuestThread> Work, ManualResetEventSlim Done)> _work = new();
    readonly SemaphoreSlim _pending = new(0);
    bool _stop;
    Exception? _failure;

    public sealed record Parser(uint Nid, MethodInfo Method, string Kind);

    /// <summary>Every SceNpCommerce2 parser NID (the C2* methods): (rec, buf, size) "root", (parent, info) "find",
    /// (parent, index, info) "index", (parent, index, out) "ptr", (parent, index, out, out) "ptr2".</summary>
    public static readonly List<Parser> Parsers = typeof(NpCommerce2).GetMethods(BindingFlags.Instance | BindingFlags.NonPublic)
        .Where(m => m.Name.StartsWith("C2", StringComparison.Ordinal) && m.Name is not ("C2CheckField" or "C2IdPrefix" or "C2IsLinkServiceId" or "C2RegisterId"))
        .SelectMany(m => m.GetCustomAttributes<HleAttribute>().Where(a => a.Library == "SceNpCommerce2").Select(a => new Parser(a.Nid, m, KindOf(m))))
        .OrderBy(p => p.Nid).ToList();

    static string KindOf(MethodInfo m)
    {
        var n = m.GetParameters().Select(p => p.Name).ToArray();
        return n switch
        {
            ["rec", "buf", "size"] => "root",
            ["parent", "info"] => "find",
            ["parent", "index", "info"] => "index",
            ["parent", "index", _] => "ptr",
            ["parent", "index", _, _] => "ptr2",
            _ => throw new InvalidOperationException(m.Name),
        };
    }

    public C2Harness(GuestMemoryFixture fx, string? firmwareModule)
    {
        _root = Path.Combine(Path.GetTempPath(), "vitasharp-c2-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(_root);
        if (firmwareModule != null)
        {
            Directory.CreateDirectory(Path.Combine(_root, "vs0", "sys", "external"));
            File.Copy(firmwareModule, Path.Combine(_root, "vs0", "sys", "external", "np_commerce2.suprx"));
        }
        _emu = new Emulator(new EmulatorOptions { FsRoot = _root, Memory = fx.Memory, EnableJit = false, CpuBackend = "interp" });
        _hle = _emu.Hle.Modules.OfType<NpCommerce2>().Single();
        _arena = _emu.Memory.Alloc(ArenaSize, "c2 test arena");
        Call(_hle, "sceNpCommerce2Init");
        if (firmwareModule == null)
        {
            return;
        }

        var lle = _emu.LoadModule("vs0:sys/external/np_commerce2.suprx");
        _thread = _emu.Kernel.CreateThread("c2-test", 0, 0x10000100, 0x40000, 0, 0x70000);
        _thread.HostBody = t =>
        {
            while (true)
            {
                _pending.Wait();
                (Action<GuestThread> Work, ManualResetEventSlim Done) w;
                lock (_work)
                {
                    if (_stop)
                    {
                        return;
                    }
                    w = _work.Dequeue();
                }
                try
                {
                    w.Work(t);
                }
                catch (Exception e)
                {
                    _failure ??= e;
                }
                w.Done.Set();
            }
        };
        _thread.Start(0, 0);
        uint init = Export(InitNid);
        // the exports are the module's own code, not HLE stubs
        if (!lle.Segments.Values.Any(sg => init >= sg.Address && init < sg.Address + sg.Size))
        {
            throw new InvalidOperationException($"sceNpCommerce2Init at 0x{init:X8} is outside np_commerce2.suprx");
        }

        int r = 0;
        OnGuest(t => r = (int)t.CallGuest(init, 0, 0, 0));
        if (r < 0)
        {
            throw new InvalidOperationException($"the firmware's sceNpCommerce2Init returned 0x{r:X8}");
        }
    }

    uint Export(uint nid) => _emu.Linker.TryGetFunctionExport(LibNid, nid, out uint a) ? a : throw new InvalidOperationException($"no export {nid:X8}");

    void OnGuest(Action<GuestThread> work)
    {
        using var done = new ManualResetEventSlim();
        lock (_work)
        {
            _work.Enqueue((work, done));
        }

        _pending.Release();
        if (!done.Wait(60_000))
        {
            throw new TimeoutException("c2 test thread");
        }

        if (_failure != null)
        {
            throw new InvalidOperationException("c2 guest call failed", _failure);
        }
    }

    static int Call(object m, string name, params object[] args) =>
        Convert.ToInt32(m.GetType().GetMethod(name, BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public)!.Invoke(m, args));

    uint Alloc(uint size)
    {
        uint p = _arena + _bump;
        _bump = (_bump + size + 15) & ~15u;
        if (_bump > ArenaSize)
        {
            throw new InvalidOperationException("c2 test arena exhausted");
        }

        GuestMemory.Fill(p, 0, size);
        return p;
    }

    int Invoke(Parser p, bool lle, params uint[] args)
    {
        if (!lle)
        {
            return Convert.ToInt32(p.Method.Invoke(_hle, args.Cast<object>().ToArray()));
        }

        uint a = Export(p.Nid);
        int r = 0;
        OnGuest(t => r = (int)t.CallGuest(a, args));
        return r;
    }

    // ------------------------------------------------------------------ replies

    static byte[] Be16(int v) => [(byte)(v >> 8), (byte)v];
    static byte[] Cat(params byte[][] parts) => parts.SelectMany(x => x).ToArray();
    static byte[] T(int tag, params byte[][] value)
    {
        var v = Cat(value);
        return Cat(Be16(tag), Be16(v.Length), v);
    }
    static byte[] Sec(int type, int count, params byte[][] items) => T(1, Be16(type), Be16(count), Cat(items));
    static byte[] Sec8(int type, int count, params byte[][] items) => T(2, Be16(type), Be16(count), Be16(0x1111), Be16(0x2222), Cat(items));
    static byte[] Z(string s) => [.. Encoding.ASCII.GetBytes(s), 0];

    /// <summary>Patterned bytes (no zero bytes, so values and times are non-zero).</summary>
    static byte[] P(int n, int seed) => Enumerable.Range(0, n).Select(i => (byte)(((seed * 31 + i * 7) % 255) + 1)).ToArray();

    /// <summary>Every tag a parser reads after an item's fixed part: strings, nested blocks and section counts.</summary>
    static readonly int[] StringTags =
    [
        0x03, 0x04, 0x05, 0x07, 0x08, 0x09, 0x0A, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11, 0x12, 0x14, 0x15, 0x2D, 0x31, 0x36, 0x38,
        0x3A, 0x3C, 0x3F, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x4F, 0x50, 0x51, 0x52, 0x54, 0x55, 0x59, 0x5A, 0x5C,
        0x5D, 0x60, 0x62, 0x65, 0x66, 0x6A, 0x6C, 0x6E, 0x76, 0x77, 0x79, 0x7D, 0x7E, 0x82, 0x84, 0x92, 0x94, 0x97, 0xA6, 0xB7, 0xB8,
    ];

    static readonly int[] CountTypes =
    [
        0x11, 0x15, 0x16, 0x17, 0x18, 0x23, 0x24, 0x25, 0x2E, 0x37, 0x38, 0x39, 0x3B, 0x3D, 0x3E, 0x58, 0x5C, 0x61, 0x64, 0x6B,
        0x6D, 0x6F, 0x74, 0x78, 0x7A, 0x7B, 0x80, 0x85, 0x90, 0x95, 0x96, 0x9B, 0x9C, 0x9D,
    ];

    /// <summary>The strings read inside the nested blocks (0x4B, 0x91, 0x63 and what follows a 0x56 / 0x8D price).</summary>
    static readonly int[] NestedTags = [0x07, 0x38, 0x44, 0x46, 0x47, 0x55, 0x59, 0x5A, 0x62, 0x92, 0xB7, 0xB8];

    static byte[] Strings(int[] tags, int seed) => Cat(tags.Select(t => T(t, Z($"s{t:X2}.{seed:D4}"))).ToArray());

    static byte[] Tail(int seed)
    {
        var n = Cat(Strings(NestedTags, seed), T(0x4A, P(0xC, seed + 1)), Sec(0x9D, 3), Sec(0x80, 2));
        return Cat(
            Strings(StringTags, seed),
            T(0x4B, P(8, seed + 2), n), T(0x91, P(8, seed + 3), n),
            T(0x56, P(0x14, seed + 4), T(0x4B, P(8, seed + 5), n), n), T(0x8D, P(0x14, seed + 6), T(0x91, P(8, seed + 7), n), n),
            T(0x58, P(8, seed + 8)), T(0x63, P(0x10, seed + 9), n), T(0x83, P(0x14, seed + 10)), T(0x98, P(0x14, seed + 11)),
            T(0x4A, P(0xC, seed + 12)), T(0x18, P(0x20, seed + 13)),
            Cat(CountTypes.Select(c => Sec(c, (c & 7) + 1)).ToArray()));
    }

    /// <summary>The tags a parser looks items up by (plain, tag-1 and tag-2 sections).</summary>
    static readonly int[] ItemTags =
    [
        0x15, 0x16, 0x17, 0x18, 0x1E, 0x1F, 0x21, 0x22, 0x23, 0x24, 0x25, 0x26, 0x27, 0x28, 0x29, 0x2B, 0x2C, 0x2E, 0x2F,
        0x30, 0x32, 0x33, 0x37, 0x38, 0x39, 0x3B, 0x3D, 0x3E, 0x4B, 0x4C, 0x4D, 0x4E, 0x56, 0x58, 0x5B, 0x5C, 0x5E, 0x5F,
        0x61, 0x64, 0x67, 0x68, 0x69, 0x6B, 0x6D, 0x6F, 0x70, 0x71, 0x72, 0x73, 0x74, 0x78, 0x7A, 0x7C, 0x7F, 0x80, 0x85,
        0x87, 0x89, 0x8A, 0x8B, 0x8C, 0x8D, 0x8E, 0x8F, 0x90, 0x91, 0x95, 0x96, 0x99, 0x9B, 0x9C,
    ];

    /// <summary>A body with every item tag: a plain item, a tag-1 section of two and a tag-2 section of two. Each item is
    /// <paramref name="fixedLen"/> patterned bytes, then (<paramref name="withTail"/>) the strings, blocks and counts.</summary>
    static byte[] Body(int fixedLen, bool withTail)
    {
        byte[] Item(int tag, int seed) => T(tag, P(fixedLen, tag + seed), withTail ? Tail(tag + seed) : []);
        var plain = ItemTags.Select(t => Item(t, 0));
        var sec = ItemTags.Select(t => Sec(t, 2, Item(t, 1), Item(t, 2)));
        var sec8 = ItemTags.Select(t => Sec8(t, 2, Item(t, 3), Item(t, 4)));
        // then, for the reply records, the strings, blocks and counts at the top level (after the items, so a plain
        // item is found before a block of the same tag)
        return Cat(plain.Concat(sec).Concat(sec8).Append(withTail ? Tail(0) : []).ToArray());
    }

    static readonly Dictionary<(int, bool), byte[]> Bodies = [];

    static byte[] CachedBody(int fixedLen, bool withTail)
    {
        lock (Bodies)
        {
            return Bodies.TryGetValue((fixedLen, withTail), out var b) ? b : Bodies[(fixedLen, withTail)] = Body(fixedLen, withTail);
        }
    }

    /// <summary>A reply buffer: id, 4 + body length, the lenient flag, the body at +0x68.</summary>
    (uint Buf, uint Size) Reply(byte[] body, uint lenient)
    {
        uint size = 0x68 + (uint)body.Length;
        uint buf = Alloc(size + 16);
        GuestMemory.W32(buf, 0x1234);
        GuestMemory.W32(buf + 8, 4 + (uint)body.Length);
        GuestMemory.W32(buf + 12, lenient);
        body.CopyTo(GuestMemory.Span(buf + 0x68, body.Length));
        return (buf, size);
    }

    /// <summary>A parent record over the reply body (data and cursor at its start).</summary>
    uint Parent(uint buf, uint size, uint lenient)
    {
        uint rec = Alloc(0x100);
        GuestMemory.W32(rec, 0x1234);
        GuestMemory.W32(rec + 4, buf);
        GuestMemory.W32(rec + 8, size);
        GuestMemory.W32(rec + 12, buf + 0x68);
        GuestMemory.W32(rec + 16, size - 0x68);
        GuestMemory.W32(rec + 20, buf + 0x68);
        GuestMemory.W32(rec + 24, lenient);
        return rec;
    }

    uint Record()
    {
        uint r = Alloc(RecSize);
        for (uint i = 0; i < RecSize; i += 4)
        {
            GuestMemory.W32(r + i, Fill);
        }

        return r;
    }

    /// <summary>How far the second run of a scenario places everything (reply, records) after the first: a record
    /// word that moves by exactly this much is an address (logged relative to the reply), any other is a value.</summary>
    const uint Shift = 0x3000;

    static uint[] Words(uint rec) => Enumerable.Range(0, (int)RecSize / 4).Select(i => GuestMemory.R32(rec + (uint)i * 4)).ToArray();

    static string Dump(uint[] first, uint[] second, uint buf)
    {
        var sb = new StringBuilder();
        for (int i = 0; i < first.Length; i++)
        {
            uint v = first[i];
            string w = second[i] - v == Shift ? $"B{(int)(v - buf):+#;-#;+0}" : v == Fill ? "--" : second[i] != v ? "?" : v.ToString("X");
            sb.Append(i == 0 ? "" : " ").Append(w);
        }
        return sb.ToString();
    }

    /// <summary>The fixed part of the parser's item: where its cursor (word 5) lands on an item with nothing after it
    /// (0x40 when the parser keeps no cursor).</summary>
    int FixedLength(Parser p)
    {
        var (buf, size) = Reply(CachedBody(0x120, false), 0);
        uint parent = Parent(buf, size, 0), rec = Record();
        if (p.Kind is "root" or "ptr" or "ptr2")
        {
            return 0x40;
        }
        // the cursor is set before the strings after the fixed part are looked up (which fail on this bare item)
        Invoke(p, false, p.Kind == "find" ? [parent, rec] : [parent, 0, rec]);
        uint data = GuestMemory.R32(rec + 12), cursor = GuestMemory.R32(rec + 20);
        return cursor > data && cursor - data <= 0x120 ? (int)(cursor - data) : 0x40;
    }

    /// <summary>The log of one parser NID over every scenario.</summary>
    public List<string> Run(Parser p, bool lle)
    {
        _bump = 0;
        var log = new List<string>();
        int f = FixedLength(p);
        _bump = 0;
        void Scenario(string name, byte[] body, uint lenient, Func<uint, uint, uint, uint, uint[]> args, bool cut = false)
        {
            // twice, the second time everything Shift bytes further: the addresses tell themselves apart from values
            var runs = new List<(int R, uint Buf, uint[] Rec, uint[] Rec2)>();
            foreach (uint start in new[] { 0u, Shift })
            {
                _bump = start;
                var (buf, size) = Reply(body, lenient);
                uint parent = Parent(buf, size, lenient), rec = Record(), rec2 = Record();
                var a = args(buf, cut ? size - 1 : size, parent, rec);
                if (a.Length > 3 && a[3] == uint.MaxValue)
                {
                    a[3] = rec2;
                }

                int r = Invoke(p, lle, a);
                runs.Add((r, buf, Words(rec), Words(rec2)));
                _bump = 0;
            }
            var (r0, b0, w0, x0) = runs[0];
            log.Add($"{name}: {(r0 < 0 ? $"{r0:X8}" : $"{r0:X}")}{(runs[1].R != r0 ? " (?)" : "")}");
            log.Add("  " + Dump(w0, runs[1].Rec, b0));
            if (p.Kind == "ptr2")
            {
                log.Add("  " + Dump(x0, runs[1].Rec2, b0));
            }
        }
        byte[] full = CachedBody(f, true), bare = CachedBody(f, false), shortItems = CachedBody(Math.Max(f - 1, 0), true);
        if (p.Kind == "root")
        {
            Scenario("full", full, 0, (b, s, _, r) => [r, b, s]);
            Scenario("full lenient", full, 1, (b, s, _, r) => [r, b, s]);
            Scenario("bare", bare, 0, (b, s, _, r) => [r, b, s]);
            Scenario("empty", [], 0, (b, s, _, r) => [r, b, s]);
            Scenario("cut", full, 0, (b, s, _, r) => [r, b, s], cut: true);
            Scenario("null rec", full, 0, (b, s, _, _) => [0, b, s]);
            Scenario("null buf", full, 0, (_, s, _, r) => [r, 0, s]);
            return log;
        }
        foreach (uint index in p.Kind == "find" ? new uint[] { 0 } : [0, 1, 2])
        {
            uint[] A(uint parent, uint rec) => p.Kind switch
            {
                "find" => [parent, rec],
                "ptr2" => [parent, index, rec, uint.MaxValue],
                _ => [parent, index, rec],
            };
            Scenario($"[{index}] full", full, 0, (_, _, pa, r) => A(pa, r));
            Scenario($"[{index}] full lenient", full, 1, (_, _, pa, r) => A(pa, r));
            Scenario($"[{index}] bare", bare, 0, (_, _, pa, r) => A(pa, r));
            Scenario($"[{index}] short", shortItems, 0, (_, _, pa, r) => A(pa, r));
            Scenario($"[{index}] empty", [], 0, (_, _, pa, r) => A(pa, r));
        }
        Scenario("null parent", full, 0, (_, _, _, r) => p.Kind switch { "find" => [0, r], "ptr2" => [0, 0, r, uint.MaxValue], _ => [0, 0, r] });
        Scenario("null info", full, 0, (_, _, pa, _) => p.Kind switch { "find" => [pa, 0], "ptr2" => [pa, 0, 0, uint.MaxValue], _ => [pa, 0, 0] });
        return log;
    }

    public static string Hash(List<string> log) =>
        Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(string.Join("\n", log))))[..16];

    public void Dispose()
    {
        if (_thread != null)
        {
            lock (_work)
            {
                _stop = true;
            }

            _pending.Release();
            _thread.WaitForExit(10_000);
        }
        _emu.Dispose();
        try
        {
            Directory.Delete(_root, true);
        }
        catch (IOException) { }
    }
}

static class C2Firmware
{
    static readonly Lazy<string?> _path = new(() =>
        JsonFirmware.ModulePath is { } json && Path.Combine(Path.GetDirectoryName(json)!, "np_commerce2.suprx") is var p && File.Exists(p) ? p : null);
    public static string? ModulePath => _path.Value;
}

public sealed class C2FirmwareFactAttribute : FactAttribute
{
    public C2FirmwareFactAttribute()
    {
        if (C2Firmware.ModulePath == null)
        {
            Skip = $"np_commerce2.suprx not found (set {EnvVars.FirmwareDir} to a Vita3K data folder or vs0, or {EnvVars.FirmwarePup})";
        }
    }
}
